package org.hakim.omega.companion

import android.content.Context
import android.net.Uri
import java.security.MessageDigest

/**
 * طبقة حوكمة محلية للمتصفح المملوك.
 * لا تدّعي أنها تغيّر system/developer instructions لدى المنصة؛ بل تجعل كل رسالة
 * يرسلها المستخدم من المتصفح المملوك تمر أولًا عبر عقد حكيم المحلي.
 */
object HakimAiGovernance {
    const val VERSION = "1.0.0"
    const val MARKER = "[[HAKIM::GOVERNED::v1]]"

    private val supportedHosts = setOf(
        "chatgpt.com",
        "chat.openai.com",
        "gemini.google.com",
        "claude.ai",
        "copilot.microsoft.com",
        "www.perplexity.ai",
        "perplexity.ai",
    )

    fun isSupportedUrl(rawUrl: String?): Boolean {
        val host = runCatching { Uri.parse(rawUrl.orEmpty()).host.orEmpty().lowercase() }.getOrDefault("")
        return host in supportedHosts
    }

    fun prepare(context: Context, rawPrompt: String, pageUrl: String?): String {
        val prompt = rawPrompt.trim()
        if (prompt.isBlank() || prompt.startsWith(MARKER)) return rawPrompt
        if (!isSupportedUrl(pageUrl)) return rawPrompt

        val prefs = context.getSharedPreferences("hakim_ai_governance", Context.MODE_PRIVATE)
        val conversationKey = conversationKey(pageUrl.orEmpty())
        val seeded = prefs.getStringSet("seeded_conversations", emptySet()).orEmpty().toMutableSet()
        val firstTurn = conversationKey !in seeded
        if (firstTurn) {
            seeded += conversationKey
            // Bound the durable set so browser history cannot grow preferences forever.
            while (seeded.size > 120) seeded.remove(seeded.first())
            prefs.edit().putStringSet("seeded_conversations", seeded).apply()
        }
        prefs.edit()
            .putString("last_governed_host", runCatching { Uri.parse(pageUrl).host }.getOrNull())
            .putLong("governed_turns", prefs.getLong("governed_turns", 0L) + 1L)
            .apply()

        val policy = if (firstTurn) FULL_KERNEL else TURN_KERNEL
        return buildString(policy.length + prompt.length + 128) {
            append(MARKER).append('\n')
            append(policy.trim()).append("\n\n")
            append("[مقصد المستخدم في هذه الرسالة]\n")
            append(prompt)
        }
    }

    fun status(context: Context): String {
        val prefs = context.getSharedPreferences("hakim_ai_governance", Context.MODE_PRIVATE)
        val turns = prefs.getLong("governed_turns", 0L)
        val host = prefs.getString("last_governed_host", null) ?: "لا يوجد"
        return "حوكمة الذكاء: نشطة محليًا v$VERSION — الرسائل المحكومة: $turns — آخر منصة: $host"
    }

    private fun conversationKey(rawUrl: String): String {
        val uri = runCatching { Uri.parse(rawUrl) }.getOrNull()
        val host = uri?.host.orEmpty().lowercase()
        val path = uri?.path.orEmpty().take(320)
        val raw = "$host|$path"
        val digest = MessageDigest.getInstance("SHA-256").digest(raw.toByteArray(Charsets.UTF_8))
        return digest.joinToString("") { "%02x".format(it) }.take(32)
    }

    /**
     * يُرسل مرة واحدة لكل مسار محادثة جديد داخل المتصفح، لذلك لسنا مقيدين بخانة
     * التعليمات المخصصة ذات السعة الصغيرة، مع بقاء قواعد المنصة الأعلى دائمًا.
     */
    private const val FULL_KERNEL = """
