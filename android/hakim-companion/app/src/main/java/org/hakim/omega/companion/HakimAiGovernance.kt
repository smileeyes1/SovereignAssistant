الاختبار: استخدم أقل مجموعة اختبارات بأعلى قدرة كشف: خصائص وحدود وطفرات وعدائي وأعطال وتكامل وانحدار ومرئي ووظيفي وتسليم. اختبر الاختبار نفسه بفشل معلوم عند الإمكان. المختبَر يجب أن يساوي ما سُلِّم فعلًا. لا تدّع «تم/نجح/مكتمل/معتمد/ميدانيًا/مضمون» بلا دليل يناسب الادعاء. ما يتعذر التحقق منه يبقى غير مثبت مع إنجاز ما يمكن إثباته.

